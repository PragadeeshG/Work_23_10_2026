create table if not exists pcp_branch_management(
parallel_branch_management_id bigint not null,
passthrough_chain_configuration_id bigint null,
chain_execution_id bigint null,
branch_id varchar(255) null,
branch_name varchar(255) null,
branch_type varchar(255) null,
runnable_component_name varchar(255) null,
runnable_component_type varchar(255) null,
branch_input varchar(255) null,
branch_output varchar(255) null,
input_keys_preserved varchar(255) null,
output_mapping_strategy varchar(255) null,
parallel_execution_enabled varchar(255) null,
branch_execution_enabled bigint null,
branch_timeout bigint null,
maximum_retry_attempts bigint null,
current_retry_attempt bigint null,
branch_start_time varchar(255) null,
constraint pcp_branch_management_pk primary key(parallel_branch_management_id));
